DEFAULT_IMG = "default.jpg"


def clean_text(s):
    return (s or "").lower()


def pick_image(name, desc):
    """Возвращает имя картинки по первому совпадению."""
    name_l = clean_text(name)
    desc_l = clean_text(desc)
    # Сначала смотрим название — оно важнее
    for img, keywords in CATEGORIES:
        for kw in keywords:
            if kw in name_l:
                return img
    # Потом описание
    for img, keywords in CATEGORIES:
        for kw in keywords:
            if kw in desc_l:
                return img
    return DEFAULT_IMG


def main():
    if not os.path.exists(ZONES_FILE):
        print(f"❌ Не найден {ZONES_FILE}")
        return

    # Бэкап
    with open(ZONES_FILE, "r", encoding="utf-8") as f:
        raw = f.read()
    with open(BACKUP_FILE, "w", encoding="utf-8") as f:
        f.write(raw)
    print(f"💾 Бэкап сохранён: {BACKUP_FILE}")

    data = json.loads(raw)

    total = 0
    stats = {}

    for region, zones in data.items():
        if not isinstance(zones, list):
            continue
        for zone in zones:
            img = pick_image(zone.get("name"), zone.get("desc"))
            zone["img"] = img
            stats[img] = stats.get(img, 0) + 1
            total += 1

    # Сохраняем
    with open(ZONES_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"\n✅ Обработано зон: {total}")
    print("\n📊 Распределение по категориям:")
    for img, count in sorted(stats.items(), key=lambda x: -x[1]):
        print(f"   {img:25s} — {count}")


if __name__ == "__main__":
    main()