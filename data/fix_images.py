def determine_img(name, desc, current_img):
    text = (name + ' ' + desc).lower()
    for pattern, img in rules:
        if re.search(pattern, text):
            return img
    # Если ничего не найдено, оставляем текущий
    return current_img

# Проходим по всем локациям
for continent in data:
    for loc in data[continent]:
        name = loc.get('name', '')
        desc = loc.get('desc', '')
        current = loc.get('img', 'default.png')
        new_img = determine_img(name, desc, current)
        loc['img'] = new_img

# Сохраняем
with open('zones_fixed.json', 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

print("Готово! Исправленный файл сохранён как zones_fixed.json")